te = datasets.MNIST("./data", train=False, download=True, transform=transforms.ToTensor())
train_loader = DataLoader(tr, batch_size=128, shuffle=True)
test_loader = DataLoader(te, batch_size=128)

class MADE(nn.Module):
    def __init__(self):
        super().__init__()
        self.l1, self.l2 = nn.Linear(D, H), nn.Linear(H, D)
        in_deg, h_deg = torch.arange(D), torch.randint(1, D, (H,))
        self.register_buffer("m1", (in_deg[None, :] <= h_deg[:, None]).float())
        self.register_buffer("m2", (h_deg[:, None] < torch.arange(1, D+1)[None, :]).float())

    def forward(self, x):
        h = torch.relu(nn.functional.linear(x, self.l1.weight * self.m1, self.l1.bias))
        return nn.functional.linear(h, self.l2.weight * self.m2, self.l2.bias)

model = MADE().to(device)
opt = torch.optim.Adam(model.parameters(), lr=0.001)

for epoch in range(5):
    tot = 0
    for x, _ in train_loader:
        x = (x.view(-1, D) > 0.5).float().to(device)
        loss = nn.functional.binary_cross_entropy_with_logits(model(x), x)
        opt.zero_grad(); loss.backward(); opt.step()
        tot += loss.item()
    print(f"Epoch {epoch+1}, NLL: {tot/len(train_loader):.4f}")

model.eval()
with torch.no_grad():
    t_nll = sum(nn.functional.binary_cross_entropy_with_logits(model((x.view(-1, D) > 0.5).float().to(device)), (x.view(-1, D) > 0.5).float().to(device), reduction="sum").item() for x, _ in test_loader)
