import torch
import torch.nn as nn
import torch.nn.functional as F
import matplotlib.pyplot as plt
from torchvision import datasets, transforms
from torch.utils.data import DataLoader, Subset

device = "cuda" if torch.cuda.is_available() else "cpu"
z_dim, batch = 100, 64

class Generator(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc = nn.Linear(z_dim, 4096)
        self.blocks = nn.ModuleDict({str(r): nn.Sequential(nn.Upsample(scale_factor=2), nn.Conv2d(64,64,3,1,1), nn.LeakyReLU(0.2,True), nn.Conv2d(64,64,3,1,1), nn.LeakyReLU(0.2,True)) for r in [16,32]})
        self.rgb = nn.ModuleDict({str(r): nn.Conv2d(64,3,1) for r in [8,16,32]})

    def forward(self, z, res, alpha=1):
        x = self.fc(z).view(-1, 64, 8, 8)
        if res == 8: return torch.tanh(self.rgb["8"](x))
        for r in [16, 32]:
            old = F.interpolate(self.rgb[str(r//2)](x), scale_factor=2)
            x = self.blocks[str(r)](x)
            if r == res: return torch.tanh(alpha * self.rgb[str(r)](x) + (1-alpha) * old)

class Discriminator(nn.Module):
    def __init__(self):
        super().__init__()
        self.rgb = nn.ModuleDict({str(r): nn.Conv2d(3,64,1) for r in [8,16,32]})
        self.down = nn.ModuleDict({str(r): nn.Sequential(nn.Conv2d(64,64,3,1,1), nn.LeakyReLU(0.2,True), nn.Conv2d(64,64,3,1,1), nn.LeakyReLU(0.2,True), nn.AvgPool2d(2)) for r in [8,16,32]})
        self.fc = nn.Linear(1024, 1)

    def forward(self, img, res, alpha=1):
        if res == 8: x = self.rgb["8"](img)
        else:
            x = alpha * self.down[str(res)](self.rgb[str(res)](img)) + (1-alpha) * self.rgb[str(res//2)](F.avg_pool2d(img, 2))
            for r in range(res//2, 8, -8): x = self.down[str(r)](x)
        return self.fc(self.down["8"](x).flatten(1))

G, D = Generator().to(device), Discriminator().to(device)
go = torch.optim.Adam(G.parameters(), lr=0.0002, betas=(0.5, 0.999))
do = torch.optim.Adam(D.parameters(), lr=0.0002, betas=(0.5, 0.999))
loss_fn = nn.BCEWithLogitsLoss()

for res in [8, 16, 32]:
    ds = datasets.CIFAR10("./data", train=True, download=True, transform=transforms.Compose([transforms.Resize((res,res)), transforms.ToTensor(), transforms.Normalize((0.5,)*3, (0.5,)*3)]))
    loader = DataLoader(Subset(ds, range(2000)), batch_size=batch, shuffle=True)

    for epoch in range(2):
        for step, (real, _) in enumerate(loader):
            real, n = real.to(device), len(real)
            alpha = min(1, step / max(1, len(loader)//2)) if res > 8 else 1

            # Train D
            z = torch.randn(n, z_dim, device=device)
            d_loss = loss_fn(D(real, res, alpha), torch.ones(n, 1, device=device)) + loss_fn(D(G(z, res, alpha).detach(), res, alpha), torch.zeros(n, 1, device=device))
            do.zero_grad(); d_loss.backward(); do.step()

            # Train G
            z = torch.randn(n, z_dim, device=device)
            g_loss = loss_fn(D(G(z, res, alpha), res, alpha), torch.ones(n, 1, device=device))
            go.zero_grad(); g_loss.backward(); go.step()

        print(f"Resolution {res}, Epoch {epoch+1}, D Loss: {d_loss.item():.4f}, G Loss: {g_loss.item():.4f}")

    with torch.no_grad(): images = G(torch.randn(16, z_dim, device=device), res).cpu()
    fig, ax = plt.subplots(4, 4, figsize=(5, 5))
    for a, img in zip(ax.flat, images):
        a.imshow(((img.permute(1,2,0)+1)/2).clamp(0,1))
        a.axis("off")
    plt.suptitle(f"Generated Images - {res}x{res}"); plt.show()

print(f"Device: {device}\nGPU is recommended for faster GAN training.\nHigher resolutions require more GPU memory and training time.")

