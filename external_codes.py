loader = DataLoader(data, batch_size=128, shuffle=True)

class VAE(nn.Module):
    def __init__(self):
        super().__init__()
        self.enc = nn.Sequential(nn.Flatten(), nn.Linear(784, 256), nn.ReLU())
        self.mu, self.logvar = nn.Linear(256, 20), nn.Linear(256, 20)
        self.dec = nn.Sequential(nn.Linear(20, 256), nn.ReLU(), nn.Linear(256, 784), nn.Sigmoid())

    def forward(self, x):
        h = self.enc(x)
        mu, logvar = self.mu(h), self.logvar(h)
        z = mu + torch.exp(0.5 * logvar) * torch.randn_like(mu)
        return self.dec(z).view(-1, 1, 28, 28), mu, logvar

model = VAE().to(device)
opt = torch.optim.Adam(model.parameters(), lr=0.001)
losses = []

for epoch in range(5):
    tot = 0
    for x, _ in loader:
        x = x.to(device)
        recon, mu, logvar = model(x)
        loss = nn.functional.binary_cross_entropy(recon, x, reduction="sum") - 0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
        opt.zero_grad(); loss.backward(); opt.step()
        tot += loss.item()
    losses.append(tot / len(data))
    print(f"Epoch {epoch+1}, Loss: {losses[-1]:.4f}")

plt.plot(losses); plt.xlabel("Epoch"); plt.ylabel("Loss"); plt.title("VAE Training Loss"); plt.show()

