import torch, torch.nn as nn
from torch.utils.data import Dataset, DataLoader
from datasets import load_dataset
from collections import Counter

device = "cuda" if torch.cuda.is_available() else "cpu"
data = load_dataset("Salesforce/wikitext", "wikitext-2-raw-v1")

words = " ".join(data["train"]["text"]).split()
vocab = ["<unk>"] + [w for w, _ in Counter(words).most_common(9999)]
stoi, V = {w: i for i, w in enumerate(vocab)}, len(vocab)

tokenize = lambda split: torch.tensor([stoi.get(w, 0) for w in " ".join(data[split]["text"]).split()])
train, valid = tokenize("train"), tokenize("validation")

class TextData(Dataset):
    def __init__(self, tokens): self.t = tokens
    def __len__(self): return (len(self.t) - 1) // 40
    def __getitem__(self, i): return self.t[i*40:i*40+40], self.t[i*40+1:i*40+41]

train_loader = DataLoader(TextData(train), batch_size=32, shuffle=True)
valid_loader = DataLoader(TextData(valid), batch_size=32)

class Transformer(nn.Module):
    def __init__(self):
        super().__init__()
        self.emb, self.pos = nn.Embedding(V, 128), nn.Embedding(100, 128)
        self.tx = nn.TransformerEncoder(nn.TransformerEncoderLayer(128, 4, 256, batch_first=True), 2)
        self.fc = nn.Linear(128, V)
    def forward(self, x):
        n = x.size(1)
        mask = torch.triu(torch.ones(n, n, device=device), 1).bool()
        return self.fc(self.tx(self.emb(x) + self.pos(torch.arange(n, device=device)), mask=mask))

model = Transformer().to(device)
opt = torch.optim.Adam(model.parameters(), lr=0.0005)
loss_fn = nn.CrossEntropyLoss()

for epoch in range(3):
    model.train(); tot = 0
    for x, y in train_loader:
        x, y = x.to(device), y.to(device)
        loss = loss_fn(model(x).view(-1, V), y.view(-1))
        opt.zero_grad(); loss.backward(); opt.step()
        tot += loss.item()
    print(f"Epoch {epoch+1}, Training Loss: {tot/len(train_loader):.4f}")

def generate(prompt):
    ids = [stoi.get(w, 0) for w in prompt.split()]
    model.eval()
    with torch.no_grad():
        for _ in range(30):
            x = torch.tensor([ids[-40:]], device=device)
            ids.append(model(x)[0, -1].argmax().item())
    return " ".join(vocab[i] for i in ids)

print("\nGenerated Text:\n", generate("The history of science"))